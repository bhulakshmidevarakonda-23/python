n1=10
n2=10
op=input("Enter your operator(+,-,*,/,%,**,//):")
if op=="+":
    print("result:",n1+n2)
elif op=="-":
    print("result:",n1-n2)
elif op=="*":
    print("result:",n1*n2)
elif op=="/":
    print("result:",n1/n2)
elif op=="%":
    print("result:",n1%n2)
elif op=="**":
    print("result:",n1**n2)
elif op=="//":
    print("result:",n1//n2)
else:
    print("Invalid operator")




